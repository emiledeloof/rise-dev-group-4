namespace Rise.Client.Components;

/// <summary>
/// visual styles available for the shared <see cref="Button"/>
/// </summary>
public enum ButtonVariant
{
    /// <summary>
    /// olive green filled btn, main action of a page eg book a room or continue
    /// </summary>
    Primary,

    /// <summary>
    /// white btn with a light border, secondary action eg back to home
    /// </summary>
    Secondary,

    /// <summary>
    /// burgundy outlined btn, destructive action eg cancel booking
    /// </summary>
    Danger,
}
